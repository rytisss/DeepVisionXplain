"""Shared harness for end-to-end experiment tests.

Runs the real `src.train.train()` task on a generated digits dataset and
verifies the exported ONNX model by loading it with onnxruntime and running
inference.
"""

import numpy as np
import onnx
import onnxruntime as ort
import rootutils
from hydra import compose, initialize
from hydra.core.hydra_config import HydraConfig
from omegaconf import open_dict

from src.eval import evaluate
from src.train import train
from tests.helpers.digits_dataset import generate_classification_dataset


def run_experiment_on_digits_dataset(
    tmp_path,
    experiment: str,
    num_classes: int,
    extra_overrides: list[str],
    source_channels: int = 3,
) -> str:
    """Runs a full train() task on a generated dataset and returns the exported ONNX path."""
    splits = generate_classification_dataset(
        tmp_path / 'dataset', num_classes=num_classes, channels=source_channels
    )
    output_dir = tmp_path / 'out'

    with initialize(version_base='1.3', config_path='../../configs'):
        cfg = compose(
            config_name='train.yaml',
            return_hydra_config=True,
            overrides=[
                f'experiment={experiment}',
                f'data.train_data_dir={splits["train"]}',
                f'data.test_data_dir={splits["test"]}',
                f'data.val_data_dir={splits["val"]}',
                'data.batch_size=4',
                'trainer.accelerator=cpu',
                'trainer.min_epochs=1',
                'trainer.max_epochs=1',
                'extras.print_config=False',
                'extras.enforce_tags=False',
            ]
            + extra_overrides,
        )
        with open_dict(cfg):
            cfg.paths.root_dir = str(
                rootutils.find_root(indicator=['.git', 'pyproject.toml'])
            )
            cfg.paths.output_dir = str(output_dir)
            cfg.paths.log_dir = str(output_dir)
            cfg.logger = None
        HydraConfig().set_config(cfg)
        train(cfg)

    onnx_files = list((output_dir / 'checkpoints').glob('*.onnx'))
    assert len(onnx_files) == 1, f'expected one exported model, got {onnx_files}'
    return str(onnx_files[0])


def run_eval_on_digits_dataset(
    tmp_path,
    experiment: str,
    ckpt_path: str,
    extra_overrides: list[str],
    predict: bool = False,
) -> dict:
    """Runs the eval task (checkpoint loading + test or predict) on the dataset
    generated by a prior `run_experiment_on_digits_dataset` call, and returns
    the resulting metrics."""
    dataset = tmp_path / 'dataset'
    output_dir = tmp_path / ('eval_predict' if predict else 'eval_test')

    with initialize(version_base='1.3', config_path='../../configs'):
        cfg = compose(
            config_name='eval.yaml',
            return_hydra_config=True,
            overrides=[
                f'experiment={experiment}',
                f'model.ckpt_path={ckpt_path}',
                f'data.train_data_dir={dataset / "train"}',
                f'data.test_data_dir={dataset / "test"}',
                f'data.val_data_dir={dataset / "val"}',
                'data.batch_size=4',
                'trainer.accelerator=cpu',
                f'predict={predict}',
                'extras.print_config=False',
                'extras.enforce_tags=False',
            ]
            + extra_overrides,
        )
        with open_dict(cfg):
            cfg.paths.root_dir = str(
                rootutils.find_root(indicator=['.git', 'pyproject.toml'])
            )
            cfg.paths.output_dir = str(output_dir)
            cfg.paths.log_dir = str(output_dir)
            cfg.logger = None
        HydraConfig().set_config(cfg)
        metric_dict, _ = evaluate(cfg)
    return metric_dict


def assert_exported_classifier(
    onnx_path: str,
    class_neurons: int,
    expect_map: bool = False,
    map_size: int = 224,
):
    """Checks the exported graph and runs inference through onnxruntime.

    With `expect_map`, verifies the two-output contract consumed by EasyODM's
    ExplainableClassification: a (batch, class_neurons) probability output and a
    (batch, map_size, map_size) explainability map. Without it, a single
    (batch, class_neurons) logits output. Both cases require a dynamic batch
    dimension, checked by running batch sizes 1 and 3.
    """
    outputs = onnx.load(onnx_path).graph.output
    assert len(outputs) == (2 if expect_map else 1)
    for output in outputs:
        dim0 = output.type.tensor_type.shape.dim[0]
        assert dim0.dim_param, (
            f'output {output.name} has static batch dimension {dim0.dim_value}'
        )

    session = ort.InferenceSession(onnx_path, providers=['CPUExecutionProvider'])
    input_name = session.get_inputs()[0].name
    for batch in (1, 3):
        x = np.random.rand(batch, 3, map_size, map_size).astype(np.float32)
        results = session.run(None, {input_name: x})
        predictions = results[0]
        assert predictions.shape == (batch, class_neurons)
        if expect_map:
            # multi-head nets apply sigmoid, so predictions are probabilities
            assert (predictions >= 0).all() and (predictions <= 1).all()
            explainability_map = results[1]
            assert explainability_map.shape == (batch, map_size, map_size)
